  // Update villages based on selected tehsil
  updateVillages: function(tehsilSelectId, villageSelectId, settlementSelectId, defaultVillageText = '-- Select Village --', defaultSettlementText = '-- Select Settlement --') {
    const tehsilSelect = document.getElementById(tehsilSelectId);
    const villageSelect = document.getElementById(villageSelectId);
    const settlementSelect = document.getElementById(settlementSelectId);
    
    if (!tehsilSelect || !villageSelect) return;
    
    const selectedTehsil = tehsilSelect.value;

    // Clear existing options
    villageSelect.innerHTML = `<option value="">${defaultVillageText}</option>`;
    if (settlementSelect) {
      settlementSelect.innerHTML = `<option value="">${defaultSettlementText}</option>`;
    }

    // Add villages for selected tehsil
    if (selectedTehsil && this.villageData[selectedTehsil]) {
      const villages = this.villageData[selectedTehsil];
      
      villages.forEach(village => {
        const option = document.createElement('option');
        option.value = village;
        option.textContent = village;
        villageSelect.appendChild(option);
      });
    }
  },

  // Update settlements based on selected village
  updateSettlements: function(tehsilSelectId, villageSelectId, settlementSelectId, defaultSettlementText = '-- Select Settlement --') {
    const tehsilSelect = document.getElementById(tehsilSelectId);
    const villageSelect = document.getElementById(villageSelectId);
    const settlementSelect = document.getElementById(settlementSelectId);
    
    if (!tehsilSelect || !villageSelect || !settlementSelect) return;
    
    const selectedTehsil = tehsilSelect.value;
    const selectedVillage = villageSelect.value;

    // Clear existing options
    settlementSelect.innerHTML = `<option value="">${defaultSettlementText}</option>`;

    // Add settlements for selected village
    if (selectedTehsil && selectedVillage &&
        this.settlementData[selectedTehsil] &&
        this.settlementData[selectedTehsil][selectedVillage]) {
      const settlements = this.settlementData[selectedTehsil][selectedVillage];
      
      settlements.forEach(settlement => {
        const option = document.createElement('option');
        option.value = settlement;
        option.textContent = settlement;
        settlementSelect.appendChild(option);
      });
    }
  }
